from .config import CaptureSettings, ConfigError


def _mode(text: str) -> CaptureSettings:
    """'1280x800@60' or 'YUYV:640x400@120'."""
    match = re.fullmatch(r"(?:(\w{4}):)?(\d+)x(\d+)@(\d+(?:\.\d+)?)", text)
    if not match:
        raise argparse.ArgumentTypeError(
            f"mode must look like 1280x800@60 or YUYV:640x400@120, got {text!r}"
        )
    fourcc, w, h, fps = match.groups()
    return CaptureSettings(fourcc or "MJPG", int(w), int(h), float(fps))


def _phases(text: str) -> list[tuple[str, float]]:
    """'centre:10,left:10,right:10'."""
    out = []
    for item in text.split(","):
        name, _, seconds = item.partition(":")
        out.append((name.strip(), float(seconds or 10)))
    return out


def _load_config(args) -> config.ExperimentConfig:
    if getattr(args, "synthetic", False):
        cfg = config.quick_config("synthetic", "synthetic", args.mode or None, "synthetic")
    elif args.config:
        cfg = config.load(args.config)
    elif args.left or args.right:
        cfg = config.quick_config(args.left, args.right, args.mode or None)
    else:
        raise ConfigError(
            "give --config FILE, --left/--right DEVICE or --synthetic (see `sight-diag list`)"
        )
    if args.mode:
        mode = args.mode
        cfg.capture = CaptureSettings(
            mode.fourcc,
            mode.width,
            mode.height,
            mode.fps,
            cfg.capture.buffer_size,
            cfg.capture.controls,
        )
    if getattr(args, "experiment_id", None):
        cfg.experiment_id = args.experiment_id
    for name in getattr(args, "disable", None) or []:
        if name in cfg.processing:
            cfg.processing[name].enabled = False
    for name in getattr(args, "enable", None) or []:
        if name in cfg.processing:
            cfg.processing[name].enabled = True
    if getattr(args, "output", None):
        cfg.output_dir = args.output
    return cfg


def _add_source_args(p: argparse.ArgumentParser) -> None:
    p.add_argument(
        "-c", "--config", help="experiment config YAML (see examples/experiment.example.yaml)"
    )
    p.add_argument(
        "--left",
        help="device for cam_left (e.g. /dev/v4l/by-path/...); overrides nothing if --config",
    )
    p.add_argument("--right", help="device for cam_right")
    p.add_argument(
        "--synthetic", action="store_true", help="two synthetic test cameras (no hardware)"
    )
    p.add_argument("--mode", type=_mode, help="capture mode, e.g. 1280x800@60 or YUYV:640x400@120")
    p.add_argument("--experiment-id")
    p.add_argument(
        "--enable", action="append", help="enable a processor (quality, face, eyes, landmarks)"
    )
    p.add_argument("--disable", action="append", help="disable a processor")
    p.add_argument(
        "--output", help="output directory for recordings (default from config: experiments)"
    )


def cmd_list(args) -> int:
    cameras = discovery.discover()
    if args.json:
        print(json.dumps([c.to_dict() for c in cameras], indent=2, default=str))
    else:
        print(discovery.format_report(cameras, show_modes=not args.brief))
    return 0 if cameras else 1


def cmd_init_config(args) -> int:
    cameras = [c for c in discovery.discover() if c.capture_node]
    candidates = [c for c in cameras if c.is_candidate] or cameras
    if len(candidates) < 2 and not args.allow_single:
        print(
            f"found {len(candidates)} capture camera(s); need 2 (use --allow-single for one)",
            file=sys.stderr,
        )
        print(discovery.format_report(cameras, show_modes=False), file=sys.stderr)
        return 1
    # Ordered by USB port so the result is reproducible; the user confirms which is left.
    candidates.sort(key=lambda c: c.stable_path or "")
    cams = {}
    for cid, camera in zip(config.CAMERA_IDS, candidates[:2], strict=False):
        cams[cid] = config.CameraConfig(
            cid, camera.stable_path or "", serial=camera.usb.serial if camera.usb else None
        )
    cfg = config.ExperimentConfig(
        args.experiment_id, cams, processing=dict(config.DEFAULT_PROCESSING)
    )
    text = config.dump(cfg)
    text = (
        "# Generated by `sight-diag init-config`. Check which physical camera is cam_left\n"
        "# (user's left when facing the cameras) with `sight-diag view` and swap if needed.\n"
    ) + text
    if args.out == "-":
        print(text)
    else:
        Path(args.out).write_text(text)
        print(f"wrote {args.out}")
    return 0


def cmd_view(args) -> int:
    from .app import run_viewer
    from .session import Session

    cfg = _load_config(args)
    phases = [p for p, _ in _phases(args.phases)] if args.phases else None
    run_viewer(Session(cfg), Path(args.snapshots), args.panel_width, phases, args.raw)
    return 0


def cmd_record(args) -> int:
    from .app import run_headless
    from .session import Session

    cfg = _load_config(args)
    run_dir, summary = run_headless(
        Session(cfg),
        args.duration,
        _phases(args.phases) if args.phases else None,
        raw_video=args.raw,
    )
    print(json.dumps(summary, indent=2))
    print(f"\nrun saved to {run_dir}")
    return 0


def cmd_bench(args) -> int:
    from .app import bench_modes

    cfg = _load_config(args)
    modes = args.sweep or [cfg.capture]
    rows = bench_modes(cfg, modes, args.duration, args.process)
    if args.json_out:
        Path(args.json_out).write_text(json.dumps(rows, indent=2))
        print(f"wrote {args.json_out}")
    return 0


def cmd_calibrate(args) -> int:
    from .app import run_calibration
    from .session import Session

    cfg = _load_config(args)
    cols, rows = (int(v) for v in args.grid.lower().split("x"))
    screen = tuple(int(v) for v in args.screen.lower().split("x")) if args.screen else None
    if "landmarks" in cfg.processing and args.landmarks_hz:
        cfg.processing["landmarks"].max_hz = args.landmarks_hz
    positions = [p.strip() for p in args.head_positions.split(",") if p.strip()]
    stamp = time.strftime("%Y%m%d-%H%M%S")
    out = Path(cfg.output_dir) / cfg.experiment_id / "calibration" / stamp
    report = run_calibration(
        Session(cfg), out, (cols, rows), args.settle, args.dwell, screen, positions
    )
    print(json.dumps(report, indent=2))
    print(f"saved to {out}")
    return 0


def _size(text: str, what: str) -> tuple[float, float]:
    match = re.fullmatch(r"\s*(\d+(?:\.\d+)?)\s*x\s*(\d+(?:\.\d+)?)\s*", text or "")
    if not match:
        raise ConfigError(f"{what} must look like 510x287, got {text!r}")
    return float(match[1]), float(match[2])


def cmd_stereo(args) -> int:
    from .stereo.board import Checkerboard, render_image, render_svg

    board = Checkerboard.parse(args.board)
    if args.action == "board":
        out = Path(args.out)
        if out.suffix.lower() == ".svg":
            out.write_text(render_svg(board, _size(args.paper, "--paper")))
        else:  # an image, e.g. to show full-screen on a tablet of known pixel pitch
            cv2_write(out, render_image(board, args.px_per_mm))
        bw, bh = board.size_mm
        print(
            f"wrote {out}: {board.spec}, squares {bw:g} x {bh:g} mm. Print at 100 %, then "
            "measure one square; pass the measured size with --board if it differs."
        )
        return 0
    if args.action == "solve":
        from .stereo.capture import solve_directory

        expected = config.load(args.config).baseline_mm if args.config else None
        result = solve_directory(
            Path(args.dir), board, expected, args.pitch, Path(args.out) if args.out else None
        )
        print(json.dumps(result, indent=2))
        return 0 if "saved" in result else 1
    if args.action == "show":
        from .stereo.calibrate import StereoCalibration

        cal = StereoCalibration.load(args.dir)
        expected = config.load(args.config).baseline_mm if args.config else None
        print(json.dumps(cal.summary(expected), indent=2))
        return 0
    # capture
    from .session import Session
    from .stereo.capture import run_stereo_capture

    cfg = _load_config(args)
    stamp = time.strftime("%Y%m%d-%H%M%S")
    out = Path(cfg.output_dir) / cfg.experiment_id / "stereo" / stamp
    pitch = sum(c.pitch_deg for c in cfg.cameras.values()) / max(1, len(cfg.cameras))
    result = run_stereo_capture(
        lambda procs: Session(cfg, processors=procs),
        out,
        board,
        args.views,
        expected_baseline_mm=cfg.baseline_mm,
        pitch_deg=pitch,
    )
    print(json.dumps(result, indent=2))
    print(f"\nviews and calibration in {out}")
    return 0 if "saved" in result else 1


def cv2_write(path: Path, image) -> None:
    import cv2

    if not cv2.imwrite(str(path), image):
        raise ConfigError(f"could not write {path}")


def cmd_gaze(args) -> int:
    from .stereo.calibrate import load_rig

    if args.action == "live":
        from .session import Session
        from .stereo.gaze import HeadRayModel
        from .stereo.live import run_gaze_preview

        if not args.model:
            raise ConfigError("gaze live needs --model gaze_model_head-ray_deg1.json")
        cfg = _load_config(args)
        cfg.processing["landmarks"].max_hz = args.landmarks_hz
        for name in ("quality", "face", "eyes"):  # only the landmarks are used
            cfg.processing[name].enabled = False
        stats = run_gaze_preview(
            Session(cfg), load_rig(args.stereo), HeadRayModel.load(args.model), args.max_skew_ms
        )
        print(json.dumps(stats, indent=2))
        return 0
    if not args.run_dir or not args.screen_mm:
        raise ConfigError("gaze evaluate needs RUN_DIR and --screen-mm")
    from .stereo.evaluate import Recording, evaluate, write_report
    from .stereo.gaze import ScreenPlane

    rec = Recording.load(Path(args.run_dir))
    size_mm = _size(args.screen_mm, "--screen-mm")
    size_px = _screen_px(args, rec)
    screen = ScreenPlane.below_rig(size_mm, size_px, args.above, args.behind)
    train = rec.positions.index(args.train) if args.train else 0
    report, models = evaluate(rec, load_rig(args.stereo), screen, train, args.max_skew_ms)
    report["stereo_calibration"] = str(args.stereo)
    path = write_report(report, Path(args.run_dir))
    for degree, model in models.items():
        model.save(Path(args.run_dir) / f"gaze_model_head-ray_deg{degree}.json")
    print(json.dumps(report, indent=2))
    print(f"\nreport: {path}")
    return 0 if "error" not in report else 1


def _screen_px(args, rec) -> tuple[int, int]:
    if args.screen_px:
        w, h = _size(args.screen_px, "--screen-px")
        return int(w), int(h)
    report = Path(args.run_dir) / "calibration.json"
    if report.exists():
        w, h = json.loads(report.read_text())["screen_px"]
        return int(w), int(h)
    raise ConfigError("give --screen-px WxH (no calibration.json next to the recording)")


def cmd_summarize(args) -> int:
    from .recorder import summarize_run

    print(json.dumps(summarize_run(args.run_dir), indent=2))
    return 0


def cmd_models(args) -> int:
    if args.action == "list":
        for key, model in models.MODELS.items():
            print(f"{key:16} {models.locate(key) or 'missing'}  ({model.licence})")
        return 0
    for key in args.keys or ["face_landmarker"]:
        print(f"{key}: {models.fetch(key)}")
    return 0


def cmd_doctor(args) -> int:
    import cv2

    ok = True
    print(
        f"lynx-sight-diagnostic {__version__}, OpenCV {cv2.__version__}, "
        f"Python {sys.version.split()[0]}"
    )
    gui = "QT" in cv2.getBuildInformation() or "GTK" in cv2.getBuildInformation()
    print(f"OpenCV GUI backend: {'yes' if gui else 'NO (view/calibrate need it)'}")
    print(
        "display: "
        + (
            os.environ.get("WAYLAND_DISPLAY")
            or os.environ.get("DISPLAY")
            or "none (view needs one)"
        )
    )
    try:
        import grp

        groups = {grp.getgrgid(g).gr_name for g in os.getgroups()}
        in_video = "video" in groups or os.geteuid() == 0
        print(
            "user in 'video' group: "
            + ("yes" if in_video else "NO: sudo usermod -aG video $USER, then log in again")
        )
        ok &= in_video
    except (ImportError, KeyError):
        pass
    for key in models.MODELS:
        print(f"model {key}: {models.locate(key) or 'missing'}")
    try:
        import mediapipe  # noqa: F401

        print("mediapipe: installed (landmarks processor available)")
    except ImportError:
        print("mediapipe: not installed (optional: uv sync --extra landmarks)")
    cameras = discovery.discover()
    capture = [c for c in cameras if c.capture_node]
    print(
        f"capture cameras: {len(capture)}  "
        f"({sum(c.is_candidate for c in capture)} look like Arducam/OV9281)"
    )
    for c in capture:
        print(f"  {c.name}: {c.stable_path}  [{c.status}]")
    return 0 if ok else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="sight-diag", description="LYNX SIGHT dual-camera diagnostics"
    )
    parser.add_argument("--version", action="version", version=__version__)
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("list", help="discover cameras: nodes, stable IDs, modes, controls, status")
    p.add_argument("--json", action="store_true")
    p.add_argument("--brief", action="store_true", help="omit the mode table")
    p.set_defaults(func=cmd_list)

    p = sub.add_parser(
        "init-config", help="write an experiment config for the two detected cameras"
    )
    p.add_argument("--out", default="experiment.yaml", help="file to write, '-' for stdout")
    p.add_argument("--experiment-id", default="exp-001")
    p.add_argument("--allow-single", action="store_true")
    p.set_defaults(func=cmd_init_config)

    p = sub.add_parser("view", help="live dual preview with diagnostics overlay")
    _add_source_args(p)
    p.add_argument("--panel-width", type=int, default=640)
    p.add_argument("--snapshots", default="snapshots")
    p.add_argument(
        "--phases", help="names for phase keys 1-9 while recording, e.g. centre,left,right"
    )
    p.add_argument("--raw", action="store_true", help="also record raw video when recording (R)")
    p.set_defaults(func=cmd_view)

    p = sub.add_parser("record", help="headless timed recording of timing + detection metrics")
    _add_source_args(p)
    p.add_argument("--duration", type=float, default=30)
    p.add_argument(
        "--phases", help="guided head positions, e.g. centre:10,left:10,right:10,up:10,down:10"
    )
    p.add_argument(
        "--raw", action="store_true", help="also save raw video (MJPG .avi) + timestamps for replay"
    )
    p.set_defaults(func=cmd_record)

    p = sub.add_parser(
        "bench", help="measure achieved frame rate/drops with both cameras streaming"
    )
    _add_source_args(p)
    p.add_argument("--duration", type=float, default=10)
    p.add_argument(
        "--sweep", type=_mode, nargs="+", help="modes to test in turn, e.g. 1280x800@30 640x400@120"
    )
    p.add_argument(
        "--process", action="store_true", help="run the processing pipelines during the benchmark"
    )
    p.add_argument("--json-out")
    p.set_defaults(func=cmd_bench)

    p = sub.add_parser("calibrate", help="experimental screen-target calibration")
    _add_source_args(p)
    p.add_argument("--grid", default="3x3")
    p.add_argument("--settle", type=float, default=0.8)
    p.add_argument("--dwell", type=float, default=1.5)
    p.add_argument("--screen", help="screen size WxH if auto-detection is wrong")
    p.add_argument(
        "--head-positions",
        default="centre",
        help="repeat the grid per head position, e.g. centre,left,right,up,near; the first is "
        "fitted, the others test head compensation (`sight-diag gaze evaluate`)",
    )
    p.add_argument(
        "--landmarks-hz",
        type=float,
        default=30.0,
        help="MediaPipe rate per camera while calibrating (more pairs for stereo)",
    )
    p.set_defaults(func=cmd_calibrate)

    p = sub.add_parser(
        "stereo",
        help="stereo calibration: board, capture, solve, show",
        description="board: write a printable checkerboard (SVG) or image. capture: live capture "
        "of still, varied board views from both cameras, then solve. solve: calibrate a capture "
        "directory again. show: summarise a stereo_calibration.json.",
    )
    p.add_argument("action", choices=["board", "capture", "solve", "show"])
    p.add_argument("dir", nargs="?", help="solve: capture directory; show: calibration file")
    _add_source_args(p)
    p.add_argument("--board", default="9x6@25", help="inner corners and square mm (default 9x6@25)")
    p.add_argument("--out", help="board: file (.svg to print, .png image); solve: calibration file")
    p.add_argument("--paper", default="297x210", help="board: paper size mm (default A4 landscape)")
    p.add_argument("--px-per-mm", type=float, default=10.0, help="board: image resolution")
    p.add_argument("--views", type=int, default=20, help="capture: views to aim for")
    p.add_argument("--pitch", type=float, default=0.0, help="solve: cameras' mounting pitch, deg")
    p.set_defaults(func=cmd_stereo)

    p = sub.add_parser(
        "gaze",
        help="evaluate gaze models offline on a recorded calibration run",
        description="evaluate: fit the head-compensated stereo model (head-ray/v1) and the 2-D "
        "model on one head position of a `calibrate --head-positions ...` run and test them on "
        "the others; saves the fitted head-ray models. live: full-screen dot at the gaze point "
        "of a saved model.",
    )
    p.add_argument("action", choices=["evaluate", "live"])
    p.add_argument("run_dir", nargs="?", help="evaluate: calibration run dir (with landmarks.npz)")
    p.add_argument("--stereo", required=True, help="stereo_calibration.json")
    p.add_argument("--screen-mm", help="evaluate: visible screen area WxH in mm, measured")
    p.add_argument("--model", help="live: a gaze_model_head-ray_*.json written by evaluate")
    p.add_argument("--landmarks-hz", type=float, default=30.0, help="live: MediaPipe rate")
    _add_source_args(p)
    p.add_argument("--screen-px", help="screen WxH px (default: from calibration.json)")
    p.add_argument(
        "--above",
        type=float,
        default=15.0,
        help="mm from the rig origin (lens axes) down to the screen's top edge",
    )
    p.add_argument(
        "--behind", type=float, default=10.0, help="mm from the lenses back to the screen surface"
    )
    p.add_argument("--train", help="head position to fit on (default: the first)")
    p.add_argument(
        "--max-skew-ms",
        type=float,
        default=20.0,
        help="max capture-time difference of a left/right landmark pair",
    )
    p.set_defaults(func=cmd_gaze)

    p = sub.add_parser("summarize", help="recompute summary.json content of a recorded run")
    p.add_argument("run_dir")
    p.set_defaults(func=cmd_summarize)

    p = sub.add_parser("models", help="list or fetch pretrained models")
    p.add_argument("action", choices=["list", "fetch"])
    p.add_argument("keys", nargs="*", choices=[[], *models.MODELS], default=None)
    p.set_defaults(func=cmd_models)

    p = sub.add_parser(
        "doctor", help="check the environment: OpenCV GUI, permissions, models, cameras"
    )
    p.set_defaults(func=cmd_doctor)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except ConfigError as exc:
        print(f"config error: {exc}", file=sys.stderr)
        return 2
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
